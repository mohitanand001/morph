// Morph for Mac: connects the shared logic (daemon/core.js, the same file Linux runs) to the Mac.
// It runs inside the Mac app's JavaScriptCore. Everything that touches the Mac goes through one object, `native`,
// which the Swift side provides (mac/Sources/Bridge.swift). Tests give it a pretend `native` (test/mac-host.test.js).
//
// What it does here, and nothing else:
//   - looks at the clipboard's change counter every 300 ms. That reads no content. A new copy is noted with the app
//     that was in front at that moment, and is read only if that app may be read (never a password manager, never a
//     copy the app marked as concealed);
//   - asks which app and window are in front, so Morph knows which tool you are in;
//   - gives core.js its timers, settings file, PDF saving, updates and image tables (macOS's own text recognition).
'use strict';

function startMorphMac(native, opts) {
  const FB = globalThis.FB;
  const { createCore } = require('daemon/core.js');
  const o = opts || {};
  const POLL_MS = o.pollMs || 300;
  const FRONT_MS = o.frontMs || 700;
  const HELPER_VERSION = 100; // what the GNOME helper's version means to core.js: every feature is there
  const DEBUG = !!native.debug;
  const log = (...a) => { if (DEBUG) native.log('[morph] ' + a.join(' ')); };
  const warn = (...a) => native.log('[morph] ' + a.join(' '));

  // ---------------------------------------------------------------- timers
  // JavaScriptCore has no setTimeout of its own: the app keeps the clock and calls __morphTimer(id) back.
  const timers = new Map();
  let nextTimer = 1;
  function setTimeoutN(fn, ms) {
    const id = nextTimer++;
    timers.set(id, fn);
    native.setTimer(id, Math.max(1, Number(ms) || 1));
    return id;
  }
  function clearTimeoutN(id) {
    if (!timers.has(id)) return;
    timers.delete(id);
    native.clearTimer(id);
  }
  globalThis.__morphTimer = (id) => {
    const fn = timers.get(id);
    if (!fn) return;
    timers.delete(id);
    try { fn(); } catch (e) { warn('timer failed:', e && e.message); }
  };
  const sleep = (ms) => new Promise((r) => setTimeoutN(r, ms));

  // ---------------------------------------------------------------- the clipboard
  // Mac pasteboard types, named the way core.js names clipboard formats.
  const MIME = { 'public.html': 'text/html', 'public.utf8-plain-text': 'text/plain', 'public.rtf': 'text/rtf', 'public.png': 'image/png', 'public.tiff': 'image/tiff', 'public.jpeg': 'image/jpeg' };
  const formatsOf = (types) => (Array.isArray(types) ? types : []).map((t) => MIME[t] || String(t));
  // org.nspasteboard.ConcealedType / TransientType: the copying app says "this is a password, keep it to yourself".
  const SECRET_TYPES = /org\.nspasteboard\.(concealed|transient|autogenerated)type|com\.agilebits\.onepassword/i;
  const OWN_TYPE = 'dev.morph.own'; // Morph marks its own writes, so they are never taken for a new copy
  const parse = (s) => { try { return s ? JSON.parse(s) : null; } catch (e) { return null; } };

  let lastRead = null;
  function readClipNow() {
    const j = parse(native.readClip());
    if (!j) return null;
    const types = Array.isArray(j.types) ? j.types.map(String) : [];
    if (types.some((t) => SECRET_TYPES.test(t))) return { formats: formatsOf(types), secret: true, text: '', html: '' };
    return { formats: formatsOf(types), secret: false, text: typeof j.text === 'string' ? j.text : '', html: typeof j.html === 'string' ? j.html : '' };
  }
  const shell = {
    setPill: (spec) => { try { native.setPanel(JSON.stringify(spec)); } catch (e) { warn('setPanel failed:', e && e.message); } },
    async readClip() {
      // One read per copy: asked again for the same copy, the answer is the one already read.
      const n = native.changeCount();
      if (lastRead && lastRead.n === n) return Object.assign({}, lastRead.sh);
      const sh = readClipNow();
      lastRead = sh ? { n, sh: Object.assign({}, sh) } : null;
      return sh;
    },
    // The Mac clipboard holds several formats at once: the formatted one and plain text, so every app finds one.
    async writeBoth(html, text) {
      const ok = !!native.writeClip(String(html || ''), String(text || ''));
      if (ok) seen = native.changeCount(); // our own write: not a new copy
      return ok;
    },
    async writeClip(mime, data) { return mime === 'text/html' ? shell.writeBoth(data, '') : shell.writeBoth('', data); },
    // ⌘V in the app in front (terminals take ⌘V too, so "shift" means nothing here).
    // false: Morph may not press keys (Accessibility is off), so the card asks you to press ⌘V.
    paste: () => {
      if (!native.axTrusted()) { warn('paste: Morph is not allowed to press keys (Accessibility)'); return false; }
      setTimeoutN(() => { native.paste(); }, 60);
      return true;
    },
    async setShortcuts(list) {
      const r = parse(native.setHotkeys(JSON.stringify(Array.isArray(list) ? list : [])));
      return Array.isArray(r) ? r.map(String) : [];
    },
  };
  globalThis.__morphHotkey = (id) => { try { core.action('key:' + String(id).replace(/[^a-z]/g, '')); } catch (e) { warn('shortcut failed:', e && e.message); } };

  // ---------------------------------------------------------------- files, PDF, updates
  const dir = native.supportDir; // ~/Library/Application Support/Morph
  const settingsPath = dir + '/settings.json';
  const pad = (n) => String(n).padStart(2, '0');
  async function savePdf(doc) {
    try {
      const d = new Date(native.now ? native.now() : Date.now());
      // The file name never comes from what was copied: date and time only, no spaces.
      const base = 'Morph_' + d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate()) + '_' + pad(d.getHours()) + '.' + pad(d.getMinutes()) + '.' + pad(d.getSeconds());
      let name = base + '.pdf';
      for (let i = 2; native.exists(native.downloadsDir + '/' + name) && i < 100; i++) name = base + '_' + i + '.pdf';
      const path = native.downloadsDir + '/' + name;
      const esc = (t) => String(t || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
      const page = '<!doctype html><html><head><meta charset="utf-8"><title>' + esc(doc.title || 'Morph') + '</title>' +
        '<style>body{font:11pt -apple-system,Helvetica,Arial,sans-serif;color:#111;margin:0}table{border-collapse:collapse}td,th{border:1px solid #bbb;padding:4px 6px;vertical-align:top}pre,code{font-family:Menlo,monospace;font-size:9.5pt}pre{white-space:pre-wrap}img{max-width:100%}</style>' +
        '</head><body>' + FB.astToEmailHtml(doc.ast) + '</body></html>';
      const ok = await new Promise((resolve) => native.savePdf(page, path, (r) => resolve(!!r)));
      return ok ? { ok: true, name, path } : { ok: false };
    } catch (e) { log('PDF failed:', e && e.message); return { ok: false }; }
  }
  const UPDATE_URL = native.updateUrl || 'https://mohitanand001.github.io/morph/version.json';
  const update = {
    check() {
      return new Promise((resolve) => native.httpGet(UPDATE_URL, (status, body) => {
        if (status !== 200) return resolve(null);
        const j = parse(body);
        resolve(j && typeof j.version === 'string' && /^\d+\.\d+\.\d+(-[a-z]+\.\d+)?$/.test(j.version) ? { version: j.version } : null);
      }));
    },
    // Downloads that version's Mac app, checks its checksum, swaps it in and restarts. false: it did not happen.
    run() {
      return new Promise((resolve) => update.check().then((info) => {
        if (!info) return resolve(false);
        native.update(info.version, (ok) => resolve(!!ok));
      }));
    },
  };
  // Image tables: the Mac reads text in pictures itself (Vision), on this computer. Nothing to download.
  const ocr = {
    builtin: true,
    ready: () => !!native.canOcr,
    legacy: () => false,
    run() {
      return new Promise((resolve) => native.ocr((res) => {
        const j = typeof res === 'string' ? parse(res) : res;
        if (!j || !Array.isArray(j.texts) || !Array.isArray(j.boxes)) return resolve({ ok: false, error: (j && j.error) || 'failed' });
        const grid = FB.ocrGrid(j.texts, j.boxes);
        resolve(grid ? { ok: true, html: FB.ocrGridHtml(grid) } : { ok: false, error: 'no_table' });
      }));
    },
  };
  const uninstall = { run: async () => !!native.uninstall() };

  const core = createCore({
    platform: 'mac',
    version: native.version || '0.0.0',
    home: native.home || '',
    log,
    store: {
      read: () => native.readFile(settingsPath),
      write: (s) => { if (!native.writeFile(settingsPath, s)) warn('could not save settings'); },
    },
    shell, savePdf, update, uninstall, ocr,
    openPath: (p) => native.openPath(String(p)),
    openUri: (u) => { if (/^(https?:|mailto:)/i.test(String(u))) native.openUrl(String(u)); },
    showInFolder: (p) => native.reveal(String(p)),
    // The Mac's permissions: Accessibility (window titles, pressing ⌘V) and reading what other apps copied.
    permissions: () => ({ ax: !!native.axTrusted(), paste: String(native.pasteAccess() || 'none') }),
    openSettings: (what) => native.openSettings(String(what)),
    now: () => (native.now ? native.now() : Date.now()), // (tests give their own clock)
    setTimeout: setTimeoutN,
    clearTimeout: clearTimeoutN,
  });
  globalThis.__morphAction = (a) => {
    const s = String(a || '');
    if (!/^[a-z]+:[a-z0-9]*$/.test(s)) return;
    try { core.action(s); } catch (e) { warn('action failed:', e && e.message); }
  };

  // ---------------------------------------------------------------- the app in front
  let frontKey = '';
  let front = null;
  function frontNow() {
    const j = parse(native.frontApp());
    if (!j || !j.app) return null;
    return { app: String(j.app), name: String(j.name || ''), title: String(j.title || '') };
  }
  function checkFront() {
    const w = frontNow();
    const key = w ? w.app + '\n' + w.title : '';
    if (key === frontKey) return;
    frontKey = key;
    front = w;
    log('front app:', w ? w.app : 'none', '(title:', w ? w.title.length : 0, 'chars)'); // never the title itself
    core.focus(w ? { app: w.app, title: w.title, name: w.name } : { app: '', title: '' }, HELPER_VERSION);
  }

  // ---------------------------------------------------------------- new copies
  let seen = -1;     // the change counter last looked at
  let polling = false;
  async function checkClip() {
    const n = native.changeCount();
    if (n === seen) return; // nothing new: nothing is read
    seen = n;
    let types = (parse(native.clipTypes()) || []).map(String);
    // An app clears the clipboard, then puts its copy there: a look in between finds nothing yet. Look again.
    for (const wait of [120, 300, 700]) {
      if (types.length || native.changeCount() !== n) break;
      await sleep(wait);
      types = (parse(native.clipTypes()) || []).map(String);
    }
    if (native.changeCount() !== n) { seen = -1; return; } // a newer copy came meanwhile: that one counts
    lastRead = null; // read what is there now
    if (types.includes(OWN_TYPE)) { log('clipboard: Morph\'s own write'); return; }
    // The copy was made in the app in front just now (asked at once, before anything else can change it).
    const w = frontNow() || front;
    const from = w ? { app: w.app, title: w.title, name: w.name } : { app: '', title: '' };
    const secret = types.some((t) => SECRET_TYPES.test(t));
    // Privacy: decided by the app the copy was made in and by the copy's own marks, before anything is read.
    // macOS 15.4 and newer may ask you before an app reads what another app copied. While it would ask, nothing is
    // read in the background (an alert for every copy); picking an app in Morph reads it.
    const access = String(native.pasteAccess() || 'none');
    const hold = access === 'ask' || access === 'deny' ? access : '';
    if (!core.mayRead(from, secret, hold)) { log('clipboard: not read (copied in', from.app || 'an unknown app', ')'); return; }
    const sh = await shell.readClip();
    log('clipboard #' + n, sh ? (sh.secret ? 'secret' : sh.text.length + ' chars text, ' + sh.html.length + ' chars html') : 'unreadable');
    await core.clipboardChanged(sh && !sh.secret ? sh : (sh ? { secret: true } : null), from);
  }
  function loop(fn, ms) {
    const tick = () => { Promise.resolve().then(fn).catch((e) => warn('check failed:', e && e.message)).finally(() => setTimeoutN(tick, ms)); };
    setTimeoutN(tick, ms);
  }

  // ---------------------------------------------------------------- go
  return (async () => {
    seen = native.changeCount(); // what is there now is not "new"
    // What is on the clipboard already was copied before Morph started, in an app it can't know: it is left alone.
    await core.start(null);
    checkFront();
    log('started');
    loop(() => { if (!polling) { polling = true; return checkClip().finally(() => { polling = false; }); } }, POLL_MS);
    loop(checkFront, FRONT_MS);
    return core;
  })();
}

if (typeof module !== 'undefined') module.exports = { startMorphMac };
